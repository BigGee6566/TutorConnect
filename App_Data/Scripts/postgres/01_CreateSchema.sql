CREATE TABLE dbo.TutorAvailability
(
    AvailabilityId   integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_TutorAvailability PRIMARY KEY,
    TutorSubjectId   integer NOT NULL REFERENCES dbo.TutorSubject (TutorSubjectId),
    AvailabilityDate date    NOT NULL,
    StartTime        time(0) NOT NULL,
    EndTime          time(0) NOT NULL,
    IsBooked         smallint NOT NULL DEFAULT 0 CHECK (IsBooked IN (0,1)),
    CreatedAt        timestamp(0) NOT NULL DEFAULT dbo.sysutcdatetime(),
    CONSTRAINT CK_TutorAvailability_Times CHECK (EndTime > StartTime)
);

CREATE TABLE dbo.SessionRequest
(
    RequestId      integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_SessionRequest PRIMARY KEY,
    StudentId      integer NOT NULL REFERENCES dbo.Student (StudentId),
    TutorSubjectId integer NOT NULL REFERENCES dbo.TutorSubject (TutorSubjectId),
    AvailabilityId integer NOT NULL REFERENCES dbo.TutorAvailability (AvailabilityId),
    RequestedDate  date    NOT NULL,
    StartTime      time(0) NOT NULL,
    EndTime        time(0) NOT NULL,
    Status         extensions.citext NOT NULL DEFAULT 'Pending',
    StudentMessage extensions.citext NULL CHECK (char_length(StudentMessage) <= 500),
    CreatedAt      timestamp(0) NOT NULL DEFAULT dbo.sysutcdatetime(),
    RespondedAt    timestamp(0) NULL,
    DeclineReason  extensions.citext NULL CHECK (char_length(DeclineReason) <= 200),
    CONSTRAINT CK_SessionRequest_Status CHECK (Status IN ('Pending','Confirmed','Declined','Cancelled')),
    CONSTRAINT CK_SessionRequest_Times CHECK (EndTime > StartTime)
);

CREATE TABLE dbo.Booking
(
    BookingId            integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Booking PRIMARY KEY,
    RequestId            integer NOT NULL CONSTRAINT UQ_Booking_RequestId UNIQUE
                             REFERENCES dbo.SessionRequest (RequestId),
    AvailabilityId       integer NOT NULL REFERENCES dbo.TutorAvailability (AvailabilityId),
    BookingDate          date    NOT NULL,
    StartTime            time(0) NOT NULL,
    EndTime              time(0) NOT NULL,
    Status               extensions.citext NOT NULL DEFAULT 'Scheduled',
    CompletedAt          timestamp(0) NULL,
    CancelledAt          timestamp(0) NULL,
    CancelledByPersonId  integer NULL REFERENCES dbo.Person (PersonId),
    CancelReasonCategory extensions.citext NULL,
    CancelReason         extensions.citext NULL CHECK (char_length(CancelReason) <= 200),
    CreatedAt            timestamp(0) NOT NULL DEFAULT dbo.sysutcdatetime(),
    CONSTRAINT CK_Booking_Status CHECK (Status IN ('Scheduled','Completed','Cancelled')),
    CONSTRAINT CK_Booking_Times CHECK (EndTime > StartTime),
    CONSTRAINT CK_Booking_CancelCategory CHECK (CancelReasonCategory IS NULL OR CancelReasonCategory IN
        ('TimetableClash','Medical','ExamPreparation','AssignmentDeadline','Other')),
    CONSTRAINT CK_Booking_CancelConsistency CHECK (
        (Status = 'Cancelled' AND CancelledAt IS NOT NULL
             AND CancelledByPersonId IS NOT NULL AND CancelReasonCategory IS NOT NULL)
        OR
        (Status <> 'Cancelled' AND CancelledAt IS NULL
             AND CancelledByPersonId IS NULL AND CancelReasonCategory IS NULL))
);

CREATE TABLE dbo.TutoringSession
(
    SessionId   integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_TutoringSession PRIMARY KEY,
    BookingId   integer NOT NULL CONSTRAINT UQ_TutoringSession_BookingId UNIQUE
