/* ---------------------------------------------------------------------------
   10. Role integrity (D-05)
   --------------------------------------------------------------------------- */

CREATE OR REPLACE FUNCTION dbo.trg_student_role_integrity()
RETURNS trigger LANGUAGE plpgsql SET search_path = dbo, extensions, pg_temp
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM dbo.Tutor t WHERE t.PersonId = NEW.PersonId) THEN
        RAISE EXCEPTION 'This person is already registered as a Tutor and cannot also be a Student.';
    END IF;
    IF EXISTS (SELECT 1 FROM dbo.Person p WHERE p.PersonId = NEW.PersonId AND p.Role <> 'Student') THEN
        RAISE EXCEPTION 'Person.Role must be Student for a row in dbo.Student.';
    END IF;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION dbo.trg_tutor_role_integrity()
RETURNS trigger LANGUAGE plpgsql SET search_path = dbo, extensions, pg_temp
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM dbo.Student s WHERE s.PersonId = NEW.PersonId) THEN
        RAISE EXCEPTION 'This person is already registered as a Student and cannot also be a Tutor.';
    END IF;
    IF EXISTS (SELECT 1 FROM dbo.Person p WHERE p.PersonId = NEW.PersonId AND p.Role <> 'Tutor') THEN
        RAISE EXCEPTION 'Person.Role must be Tutor for a row in dbo.Tutor.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_Student_RoleIntegrity BEFORE INSERT OR UPDATE ON dbo.Student
    FOR EACH ROW EXECUTE FUNCTION dbo.trg_student_role_integrity();
CREATE TRIGGER trg_Tutor_RoleIntegrity BEFORE INSERT OR UPDATE ON dbo.Tutor
    FOR EACH ROW EXECUTE FUNCTION dbo.trg_tutor_role_integrity();

