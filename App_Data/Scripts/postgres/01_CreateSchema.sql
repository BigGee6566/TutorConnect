/* =============================================================================
   TutorConnect - postgres/01_CreateSchema.sql
   Target : PostgreSQL 15+ (Supabase)
   Purpose: The PostgreSQL port of ../01_CreateSchema.sql and ../02_SeedLookups.sql.

   WARNING: drops and recreates every table in schema "dbo". It is a build script,
            not a migration. Never run it against a database you want to keep.

   Port decisions - each keeps the application's SQL meaning what it meant on
   SQL Server:
     P-01  Tables live in schema "dbo", so every "dbo.Table" reference still resolves.
           Supabase's Data API exposes only "public", so nothing here is reachable
           through it; the application connects directly.
     P-02  Text columns are CITEXT. SQL Server's default collation is case-insensitive
           and sign-in, BR-01 uniqueness and search depend on it. Length limits are
           kept as CHECK constraints.
     P-03  BIT flags are SMALLINT restricted to 0/1, so "IsActive = 1" stays valid.
     P-04  DATETIME2(0) becomes timestamp(0) holding UTC. dbo.sysutcdatetime() keeps
           the SQL Server name used throughout the queries.
     P-05  The role-integrity triggers (D-05) become BEFORE INSERT OR UPDATE row
           triggers - PostgreSQL has them, so no set-based workaround is needed.
     D-07  No password literal appears here. Accounts are created by the application.
   ============================================================================= */

CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA extensions;
CREATE SCHEMA IF NOT EXISTS dbo;

DROP TABLE IF EXISTS dbo.AuditLog, dbo.PostponementRequest, dbo.Review, dbo.TutoringSession,
    dbo.Booking, dbo.SessionRequest, dbo.TutorAvailability, dbo.TutorSubject,
    dbo.StudentSubject, dbo.Notification, dbo.Tutor, dbo.Student, dbo.StudyLevel,
    dbo.Subject, dbo.Person CASCADE;

/* ---------------------------------------------------------------------------
   0. SQL Server-named helpers used by the application's queries
   --------------------------------------------------------------------------- */

-- UTC "now", second precision, as SYSUTCDATETIME() was stored in DATETIME2(0).
CREATE OR REPLACE FUNCTION dbo.sysutcdatetime()
RETURNS timestamp(0) LANGUAGE sql STABLE
AS $$ SELECT (now() AT TIME ZONE 'UTC')::timestamp(0) $$;

-- Local wall-clock "now". The application is South African, so local means SAST.
CREATE OR REPLACE FUNCTION dbo.getdate()
RETURNS timestamp(0) LANGUAGE sql STABLE
AS $$ SELECT (now() AT TIME ZONE 'Africa/Johannesburg')::timestamp(0) $$;

/* ---------------------------------------------------------------------------
