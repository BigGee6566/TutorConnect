CREATE TABLE dbo.Person
(
    PersonId         integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Person PRIMARY KEY,
    UserName         extensions.citext NOT NULL CONSTRAINT UQ_Person_UserName UNIQUE
                         CONSTRAINT CK_Person_UserName_Len CHECK (char_length(UserName) <= 50),
    FirstName        extensions.citext NOT NULL CHECK (char_length(FirstName) <= 50),
    LastName         extensions.citext NOT NULL CHECK (char_length(LastName) <= 50),
    Gender           extensions.citext NOT NULL CONSTRAINT CK_Person_Gender
                         CHECK (Gender IN ('Male','Female','Other')),
    EmailAddress     extensions.citext NOT NULL CONSTRAINT UQ_Person_Email UNIQUE
                         CHECK (char_length(EmailAddress) <= 100),
    CellNumber       extensions.citext NOT NULL CHECK (char_length(CellNumber) <= 15),
    PasswordHash     bytea    NOT NULL CHECK (octet_length(PasswordHash) <= 64),
    PasswordSalt     bytea    NOT NULL CHECK (octet_length(PasswordSalt) <= 32),
    HashIterations   integer  NOT NULL DEFAULT 100000,
    Location         extensions.citext NOT NULL CHECK (char_length(Location) <= 100),
    Role             extensions.citext NOT NULL CONSTRAINT CK_Person_Role
                         CHECK (Role IN ('Student','Tutor','Administrator')),
    IsActive         smallint NOT NULL DEFAULT 1 CHECK (IsActive IN (0,1)),
    FailedLoginCount integer  NOT NULL DEFAULT 0,
    LockoutEndUtc    timestamp(0) NULL,
    CreatedAt        timestamp(0) NOT NULL DEFAULT dbo.sysutcdatetime(),
    UpdatedAt        timestamp(0) NULL
);

CREATE TABLE dbo.Student
(
    StudentId  integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Student PRIMARY KEY,
    StudentNo  extensions.citext NOT NULL CONSTRAINT UQ_Student_StudentNo UNIQUE
                   CHECK (char_length(StudentNo) <= 20),
    PersonId   integer NOT NULL CONSTRAINT UQ_Student_PersonId UNIQUE,
    CreatedAt  timestamp(0) NOT NULL DEFAULT dbo.sysutcdatetime(),
    CONSTRAINT FK_Student_Person FOREIGN KEY (PersonId)
        REFERENCES dbo.Person (PersonId) ON DELETE CASCADE
);

CREATE TABLE dbo.Tutor
(
    TutorId         integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Tutor PRIMARY KEY,
    PersonId        integer NOT NULL CONSTRAINT UQ_Tutor_PersonId UNIQUE,
    Qualification   extensions.citext NOT NULL CHECK (char_length(Qualification) <= 100),
    ExperienceYears integer NOT NULL CONSTRAINT CK_Tutor_ExperienceYears CHECK (ExperienceYears >= 0),
    RatePerSession  numeric(10,2) NOT NULL CONSTRAINT CK_Tutor_Rate CHECK (RatePerSession >= 0),
    Bio             extensions.citext NULL CHECK (char_length(Bio) <= 1000),
    IsApproved      smallint NOT NULL DEFAULT 0 CHECK (IsApproved IN (0,1)),
    ApprovedAt      timestamp(0) NULL,
    CreatedAt       timestamp(0) NOT NULL DEFAULT dbo.sysutcdatetime(),
    CONSTRAINT FK_Tutor_Person FOREIGN KEY (PersonId)
        REFERENCES dbo.Person (PersonId) ON DELETE CASCADE
);

